const root = fileURLToPath(new URL('../', import.meta.url))

test('versions compare numerically, part by part', () => {
  assert.deepEqual(parseVersion('1.20.3'), [1, 20, 3])
  assert.ok(compareVersions('0.2.0', '0.1.0') > 0)
  assert.ok(compareVersions('0.10.0', '0.9.9') > 0)
  assert.ok(compareVersions('1.0.0', '0.99.99') > 0)
  assert.ok(compareVersions('0.1.1', '0.1.0') > 0)
  assert.ok(compareVersions('0.1.0', '0.2.0') < 0)
  assert.equal(compareVersions('0.2.0', '0.2.0'), 0)
  assert.throws(() => parseVersion('v0.2.0'), /without the "v": 0.2.0/)
  assert.throws(() => parseVersion('0.2'), /not a version/)
  assert.throws(() => parseVersion('0.2.0-beta.1'), /not a version/)
  assert.throws(() => parseVersion('01.2.0'), /not a version/)
})

const conf = `{
  "$schema": "https://schema.tauri.app/config/2",
  "productName": "Kimochi",
  "version": "0.1.0",
  "plugins": { "other": { "version": "9.9.9" } }
}
`
const toml = `[package]
name = "kimochi"
version = "0.1.0"
edition = "2021"

[dependencies]
tauri = { version = "2", features = [] }

[dependencies.other]
version = "0.1.0"
`
const lock = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "kimochi"
version = "0.1.0"
dependencies = [
 "tauri",
]

[[package]]
name = "kimochi-capture"
version = "0.1.0"
`
const changelog = `# Changelog

## [Unreleased]

### Added

- Updates.
`

test('each file has only its own version changed, layout kept', () => {
  const c = bumpTauriConf(conf, '0.2.0')
  assert.equal(c.current, '0.1.0')
  assert.equal(c.text, conf.replace('"version": "0.1.0"', '"version": "0.2.0"'))

  const t = bumpCargoToml(toml, '0.2.0')
  assert.equal(t.current, '0.1.0')
  assert.equal(t.text, toml.replace('name = "kimochi"\nversion = "0.1.0"', 'name = "kimochi"\nversion = "0.2.0"'))

  const l = bumpCargoLock(lock, '0.2.0')
  assert.equal(l.current, '0.1.0')
  assert.equal(l.text, lock.replace('name = "kimochi"\nversion = "0.1.0"', 'name = "kimochi"\nversion = "0.2.0"'))
  assert.match(l.text, /name = "kimochi-capture"\nversion = "0.1.0"/, 'a crate with a longer name is left alone')

  assert.throws(() => bumpCargoToml('[dependencies]\nversion = "1"\n', '0.2.0'), /no \[package\]/)
  assert.throws(() => bumpCargoLock('', '0.2.0'), /expected one "kimochi" package/)
})

test('a release plan rewrites all four files and takes its notes from the changelog', () => {
  const plan = planRelease({
    version: '0.2.0',
    date: '2026-10-13',
    files: { tauriConf: conf, cargoToml: toml, cargoLock: lock, changelog }
  })
  assert.equal(plan.current, '0.1.0')
  assert.equal(plan.tag, 'v0.2.0')
  assert.equal(plan.notes, '### Added\n\n- Updates.')
  assert.equal(plan.commitMessage, 'Kimochi 0.2.0')
  assert.equal(plan.tagMessage, 'Kimochi 0.2.0\n\n### Added\n\n- Updates.\n')
  assert.match(plan.files.changelog, /## \[Unreleased\]\n\n## \[0\.2\.0\] - 2026-10-13\n\n### Added/)
  assert.match(plan.files.tauriConf, /"version": "0.2.0"/)
})

test('a release plan refuses a version that is not newer, drifted files and an empty changelog', () => {
  const files = { tauriConf: conf, cargoToml: toml, cargoLock: lock, changelog }
  const plan = (version, overrides = {}) => planRelease({ version, date: '2026-10-13', files: { ...files, ...overrides } })
  assert.throws(() => plan('0.1.0'), /0.1.0 is not greater than the current version 0.1.0/)
  assert.throws(() => plan('0.0.9'), /not greater/)
  assert.throws(() => plan('v0.2.0'), /without the "v"/)
  assert.throws(() => plan('0.2.0', { cargoToml: toml.replace('0.1.0', '0.1.5') }), /Cargo.toml says 0.1.5/)
  assert.throws(() => plan('0.2.0', { changelog: '# Changelog\n\n## [Unreleased]\n' }), /nothing under Unreleased/)
})

/** A fake `git` answering from a table keyed by the joined arguments. */
function fakeGit(overrides = {}) {
  const answers = {
    'symbolic-ref --short -q HEAD': { stdout: 'main\n' },
    'status --porcelain': { stdout: '' },
    'fetch --quiet origin main': { stdout: '' },
    'rev-parse HEAD': { stdout: 'abc\n' },
    'rev-parse refs/remotes/origin/main': { stdout: 'abc\n' },
    'rev-list --left-right --count HEAD...refs/remotes/origin/main': { stdout: '0\t0\n' },
    'rev-parse -q --verify refs/tags/v0.2.0': { status: 1, stdout: '' },
    'ls-remote --tags origin refs/tags/v0.2.0': { stdout: '' },
    ...overrides
  }
  const calls = []
  const git = (args) => {
    const key = args.join(' ')
    calls.push(key)
    if (!(key in answers)) throw new Error(`unexpected git ${key}`)
    return { status: 0, stderr: '', ...answers[key] }
  }
  return { git, calls }
}

test('the checks pass on a clean main that matches origin, with the tag free', () => {
  const { git, calls } = fakeGit()
  assert.deepEqual(preflight({ tag: 'v0.2.0', git }), { head: 'abc' })
  assert.ok(calls.includes('fetch --quiet origin main'), 'compares against a fresh origin/main')
})

test('each check refuses with what to do', () => {
  const check = (overrides, options = {}) => preflight({ tag: 'v0.2.0', git: fakeGit(overrides).git, ...options })
  assert.throws(() => check({ 'symbolic-ref --short -q HEAD': { stdout: 'feature\n' } }), /cut from main; this checkout is on feature/)
  assert.throws(() => check({ 'symbolic-ref --short -q HEAD': { status: 1, stdout: '' } }), /detached HEAD/)
  assert.throws(() => check({ 'status --porcelain': { stdout: ' M README.md\n' } }), /not clean[\s\S]*README.md/)
  assert.doesNotThrow(() => check({ 'status --porcelain': { stdout: ' M README.md\n' } }, { skipClean: true }))
  assert.throws(() => check({ 'fetch --quiet origin main': { status: 128, stderr: 'no network' } }), /fetch .* failed: no network/)
  assert.throws(
    () =>
      check({
        'rev-parse HEAD': { stdout: 'def\n' },
        'rev-list --left-right --count HEAD...refs/remotes/origin/main': { stdout: '2\t1\n' }
      }),
    /2 commit\(s\) ahead of and 1 behind origin\/main/
  )
  assert.throws(() => check({ 'rev-parse -q --verify refs/tags/v0.2.0': { stdout: 'abc\n' } }), /v0.2.0 already exists here/)
  assert.throws(
    () => check({ 'ls-remote --tags origin refs/tags/v0.2.0': { stdout: 'abc\trefs/tags/v0.2.0\n' } }),
    /already exists on origin/
  )
})

test('the GitHub repository is read from https and ssh remotes', () => {
  assert.equal(githubRepo('https://github.com/hamstu/kimochi-tauri.git\n'), 'hamstu/kimochi-tauri')
  assert.equal(githubRepo('git@github.com:hamstu/kimochi-tauri.git'), 'hamstu/kimochi-tauri')
  assert.equal(githubRepo('https://github.com/hamstu/kimochi-tauri'), 'hamstu/kimochi-tauri')
  assert.equal(githubRepo('https://example.com/x.git'), null)
})

test("the repository's own files can be bumped, and agree on the current version", async () => {
  const read = (file) => readFile(`${root}${file}`, 'utf8')
  const current = bumpTauriConf(await read(FILES.tauriConf), '999.0.0').current
  assert.equal(bumpCargoToml(await read(FILES.cargoToml), '999.0.0').current, current)
  assert.equal(bumpCargoLock(await read(FILES.cargoLock), '999.0.0').current, current)
})

test('CI takes release notes from the changelog, checks the tag first and publishes last', async () => {
  const ci = await readFile(`${root}.github/workflows/ci.yml`, 'utf8')
  const pkg = JSON.parse(await readFile(`${root}package.json`, 'utf8'))
  assert.equal(pkg.scripts.release, 'node scripts/cut-release.mjs')
  assert.equal(pkg.scripts['release:bundle'], 'node scripts/run.mjs release')
  assert.match(ci, /run: npm run \$\{\{ needs\.plan\.outputs\.script \}\}/, 'release mode bundles with release:bundle')
  assert.match(ci, /const script = mode === 'release' \? 'release:bundle' : 'bundle'/)
  assert.match(ci, /\[\[ "\$tag" != "v\$version" \]\]/, 'the plan job refuses a tag that does not match the version')
  assert.match(ci, /node scripts\/changelog\.mjs section "\$version" > \.\.\/release-notes\.md/)
  assert.match(ci, /--notes-file \.\.\/release-notes\.md/)
  assert.doesNotMatch(ci, /--generate-notes/)
  const manifest = ci.slice(ci.indexOf('\n  manifest:'))
  assert.match(manifest, /if: needs\.plan\.outputs\.mode == 'release' && needs\.plan\.outputs\.rolling == 'false'/)
  assert.ok(
    manifest.indexOf('gh release edit "$RELEASE" --draft=false --latest') > manifest.indexOf('gh release delete-asset'),
    'publishing is the last step, after latest.json is uploaded and the sidecars removed'
  )
})
